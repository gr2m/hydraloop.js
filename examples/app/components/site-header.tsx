"use client";

import Link from "next/link";
import { usePathname } from "next/navigation";

import { signOut } from "@/app/actions";
import type { DeviceInfo } from "@/lib/model";

export function SiteHeader({
  device,
  demo,
}: {
  device: DeviceInfo;
  demo: boolean;
}) {
  const pathname = usePathname();
  return (
    <header className="site-header">
      <div className="site-identity">
        <span className="site-device">{device.name}</span>
        <span className="site-meta">
          {[
            device.type,
            device.serial,
            device.firmware && `firmware ${device.firmware}`,
          ]
            .filter(Boolean)
            .join(" · ")}
        </span>
        {demo && (
          <span
            className="tag is-demo"
            title="Generated by a simulation, not measured"
          >
            Simulated data
          </span>
        )}
      </div>
      <nav className="site-nav" aria-label="Views">
        <Link href="/" aria-current={pathname === "/" ? "page" : undefined}>
          Overview
        </Link>
        <Link
          href="/live"
          aria-current={pathname === "/live" ? "page" : undefined}
        >
          Live
        </Link>
        <Link
          href="/history"
          aria-current={pathname === "/history" ? "page" : undefined}
        >
          History
        </Link>
        <form action={signOut}>
          <button type="submit" className="link-button">
            Sign out
          </button>
        </form>
      </nav>
    </header>
  );
}
