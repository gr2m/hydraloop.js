#!/usr/bin/env node
// Generates the endpoint methods and types of the internal SDK
// (`hydraloop/internal`) from the OpenAPI specs in spec/internal/.
// Run with: node scripts/generate-internal.js
//
// Writes, for each of the two APIs ("root" and "local"):
//   lib/internal/<api>/<tag>.js    one function per operation of the tag
//   lib/internal/<api>/index.js    binds all functions to the SDK state
//   lib/internal/<api>-types.d.ts  schema types and the method signatures
//
// It also writes the list of all methods into readme.internal.md. Everything
// else in lib/internal/ is written by hand.

import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT_DIR = join(__dirname, "..");
const LIB_DIR = join(ROOT_DIR, "lib", "internal");
const README_PATH = join(ROOT_DIR, "readme.internal.md");

const APIS = [
  {
    name: "root",
    spec: "spec/internal/root-api.json",
    typeName: "RootApi",
    requestFn: "rootRequest",
  },
  {
    name: "local",
    spec: "spec/internal/local-api.json",
    typeName: "LocalApi",
    requestFn: "localRequest",
  },
];

const METHODS = ["get", "post", "put", "patch", "delete"];
const METHODS_WITH_BODY = ["post", "put", "patch"];

const HEADER = "// Generated by scripts/generate-internal.js. Do not edit.";

/** @type {string[]} */
const methodLists = [];

for (const api of APIS) {
  const spec = JSON.parse(readFileSync(join(ROOT_DIR, api.spec), "utf8"));
  const tags = groupOperationsByTag(spec);

  rmSync(join(LIB_DIR, api.name), { recursive: true, force: true });
  mkdirSync(join(LIB_DIR, api.name), { recursive: true });

  for (const [tag, operations] of tags) {
    writeFileSync(
      join(LIB_DIR, api.name, `${kebabCase(tag)}.js`),
      generateTagModule(api, tag, operations),
    );
  }

  writeFileSync(
    join(LIB_DIR, api.name, "index.js"),
    generateIndexModule(api, tags),
  );
  writeFileSync(
    join(LIB_DIR, `${api.name}-types.d.ts`),
    generateTypes(api, spec, tags),
  );

  methodLists.push(generateMethodList(api, tags));

  const count = [...tags.values()].reduce((sum, ops) => sum + ops.length, 0);
  console.log(`${api.name}: ${count} operations in ${tags.size} namespaces`);
}

const readme = readFileSync(README_PATH, "utf8");
writeFileSync(
  README_PATH,
  readme.replace(
    /(<!-- BEGIN GENERATED METHODS -->\n)[\s\S]*(<!-- END GENERATED METHODS -->)/,
    `$1\n${methodLists.join("\n\n")}\n\n$2`,
  ),
);

// ── Operations ─────────────────────────────────────────────────────────────

/**
 * @typedef {{
 *   method: string,
 *   path: string,
 *   name: string,
 *   summary: string,
 *   parameters: any[],
 *   requestBody: any,
 *   hasBody: boolean,
 *   responseSchema: any,
 * }} Operation
 */

/**
 * Groups operations by their first tag. The method name is the part of the
 * operation ID after the controller name, e.g. "getData" for
 * "GraphController_getData".
 *
 * @returns {Map<string, Operation[]>}
 */
function groupOperationsByTag(spec) {
  /** @type {Map<string, Operation[]>} */
  const tags = new Map();

  for (const [path, pathItem] of Object.entries(spec.paths)) {
    for (const [method, operation] of Object.entries(pathItem)) {
      if (!METHODS.includes(method)) continue;

      const tag = operation.tags?.[0] ?? "default";
      const name = operation.operationId.split("_").slice(1).join("_");
      const requestBody =
        operation.requestBody?.content?.["application/json"]?.schema;

      if (!tags.has(tag)) tags.set(tag, []);
      const operations = /** @type {Operation[]} */ (tags.get(tag));

      if (operations.some((op) => op.name === name)) {
        throw new Error(`Duplicate method name ${tag}.${name}`);
      }

      operations.push({
        method,
        path,
        name,
        summary: operation.summary ?? "",
        parameters: operation.parameters ?? [],
        requestBody,
        hasBody: Boolean(requestBody) || METHODS_WITH_BODY.includes(method),
        responseSchema: getResponseSchema(operation),
      });
    }
  }

  return new Map([...tags].sort(([a], [b]) => a.localeCompare(b)));
}

function getResponseSchema(operation) {
  for (const [status, response] of Object.entries(operation.responses ?? {})) {
    if (!status.startsWith("2")) continue;
    const schema = response.content?.["application/json"]?.schema;
    if (schema) return schema;
  }
  return null;
}

// ── JavaScript ─────────────────────────────────────────────────────────────

/**
 * @param {typeof APIS[number]} api
 * @param {string} tagName
 * @param {Operation[]} operations
 */
function generateTagModule(api, tagName, operations) {
  const tag = camelCase(tagName);
  const functions = operations.map((op) => {
    const params = op.parameters.filter((p) => p.in !== "header");
    const optionsRequired =
      params.some((p) => p.required) || Boolean(op.requestBody);
    const optionsType = `Parameters<import("../${api.name}-types.d.ts").${api.typeName}[${JSON.stringify(tag)}][${JSON.stringify(op.name)}]>[0]`;
    const returnType = `ReturnType<import("../${api.name}-types.d.ts").${api.typeName}[${JSON.stringify(tag)}][${JSON.stringify(op.name)}]>`;

    const route = {
      method: op.method.toUpperCase(),
      url: op.path,
      ...pick(params, "path"),
      ...pick(params, "query"),
    };

    return [
      "/**",
      ...(op.summary ? [` * ${op.summary}`, " *"] : []),
      ` * \`${op.method.toUpperCase()} ${op.path}\``,
      " *",
      ` * @param {import("../index.d.ts").State} state`,
      ` * @param {${optionsType}} ${optionsRequired ? "options" : "[options]"}`,
      ` * @returns {${returnType}}`,
      " */",
      `export function ${op.name}(state, options) {`,
      `  return ${api.requestFn}(state, ${JSON.stringify(route)}, options);`,
      "}",
    ].join("\n");
  });

  return [
    "// @ts-check",
    HEADER,
    "",
    `import { ${api.requestFn} } from "../api-request.js";`,
    "",
    functions.join("\n\n"),
    "",
  ].join("\n");
}

/**
 * @param {any[]} params
 * @param {"path" | "query"} location
 */
function pick(params, location) {
  const names = params.filter((p) => p.in === location).map((p) => p.name);
  return names.length ? { [location]: names } : {};
}

/**
 * @param {typeof APIS[number]} api
 * @param {Map<string, Operation[]>} tags
 */
function generateIndexModule(api, tags) {
  const imports = [...tags.keys()].map(
    (tag) => `import * as ${camelCase(tag)} from "./${kebabCase(tag)}.js";`,
  );
  const namespaces = [...tags].map(([tag, operations]) =>
    [
      `    ${camelCase(tag)}: {`,
      ...operations.map(
        (op) =>
          `      ${op.name}: ${camelCase(tag)}.${op.name}.bind(null, state),`,
      ),
      "    },",
    ].join("\n"),
  );

  return [
    "// @ts-check",
    HEADER,
    "",
    ...imports,
    "",
    "/**",
    ` * @param {import("../index.d.ts").State} state`,
    ` * @returns {import("../${api.name}-types.d.ts").${api.typeName}}`,
    " */",
    `export function create${capitalize(api.name)}Api(state) {`,
    "  return {",
    ...namespaces,
    "  };",
    "}",
    "",
  ].join("\n");
}

// ── Readme ─────────────────────────────────────────────────────────────────

/**
 * @param {typeof APIS[number]} api
 * @param {Map<string, Operation[]>} tags
 */
function generateMethodList(api, tags) {
  const sections = [...tags].map(([tag, operations]) => {
    const namespace = `${api.name}.${camelCase(tag)}`;
    const rows = operations.map((op) => {
      const summary = op.summary.replaceAll("|", "\\|");
      return `| \`${op.name}()\` | \`${op.method.toUpperCase()} ${op.path}\` | ${summary} |`;
    });
    return [
      "<details>",
      `<summary><code>${namespace}</code> (${operations.length})</summary>`,
      "",
      "| Method | Request | Summary |",
      "| --- | --- | --- |",
      ...rows,
      "",
      "</details>",
    ].join("\n");
  });

  return [
    `### ${capitalize(api.name)} API (\`hydraloop.${api.name}\`)`,
    "",
    sections.join("\n\n"),
  ].join("\n");
}

// ── Types ──────────────────────────────────────────────────────────────────

/**
 * @param {typeof APIS[number]} api
 * @param {any} spec
 * @param {Map<string, Operation[]>} tags
 */
function generateTypes(api, spec, tags) {
  const schemas = Object.entries(spec.components?.schemas ?? {}).map(
    ([name, schema]) => {
      const description = schema.description
        ? `${docComment(schema.description, "")}\n`
        : "";

      // `DateTime` is an empty object in the spec, but the API sends and
      // accepts ISO 8601 date strings.
      if (name === "DateTime") {
        return `${description}export type DateTime = string;`;
      }

      if (schema.type === "object" && schema.properties && !schema.nullable) {
        return `${description}export interface ${name} ${objectType(schema, "")}`;
      }
      return `${description}export type ${name} = ${schemaToType(schema, "")};`;
    },
  );

  // Some schemas are referenced, but not defined in the spec
  const defined = Object.keys(spec.components?.schemas ?? {});
  const referenced = new Set(
    [...JSON.stringify(spec).matchAll(/"#\/components\/schemas\/(\w+)"/g)].map(
      (match) => match[1],
    ),
  );
  for (const name of [...referenced].sort()) {
    if (defined.includes(name)) continue;
    schemas.push(
      `/** Referenced, but not defined in the spec */\nexport type ${name} = Record<string, any>;`,
    );
  }

  const namespaces = [...tags].map(([tag, operations]) =>
    [
      `  ${camelCase(tag)}: {`,
      ...operations.map((op) => methodSignature(op)),
      "  };",
    ].join("\n"),
  );

  return [
    HEADER,
    "",
    "/**",
    " * The lazy loading event of list endpoints, e.g. `{ first: 0, rows: 10 }`.",
    " * Objects are sent as JSON.",
    " */",
    "export type LazyLoadEvent = Record<string, unknown>;",
    "",
    schemas.join("\n\n"),
    "",
    `export interface ${api.typeName} {`,
    namespaces.join("\n"),
    "}",
    "",
  ].join("\n");
}

/**
 * @param {Operation} op
 */
function methodSignature(op) {
  const indent = "    ";
  const params = op.parameters.filter((p) => p.in !== "header");
  const fields = params.map((p) => {
    const type =
      p.in === "query" && p.name === "event"
        ? "string | LazyLoadEvent"
        : p.schema?.$ref?.endsWith("/DateTime")
          ? "string | Date"
          : queryParamType(p, `${indent}  `);
    const doc = p.description
      ? `${docComment(p.description, `${indent}  `)}\n`
      : "";
    return `${doc}${indent}  ${propertyName(p.name)}${p.required ? "" : "?"}: ${type};`;
  });

  if (op.requestBody) {
    fields.push(
      `${indent}  body: ${schemaToType(op.requestBody, `${indent}  `)};`,
    );
  } else if (op.hasBody) {
    // No request body is documented, but it may still accept one.
    fields.push(`${indent}  body?: any;`);
  }

  const optional = !params.some((p) => p.required) && !op.requestBody;
  const options = fields.length
    ? `options${optional ? "?" : ""}: {\n${fields.join("\n")}\n${indent}}`
    : "options?: {}";
  const returnType = op.responseSchema
    ? schemaToType(op.responseSchema, indent)
    : "any";

  const doc = [
    `${indent}/**`,
    ...(op.summary ? [`${indent} * ${op.summary}`, `${indent} *`] : []),
    `${indent} * \`${op.method.toUpperCase()} ${op.path}\``,
    `${indent} */`,
  ].join("\n");

  return `${doc}\n${indent}${op.name}(${options}): Promise<${returnType}>;`;
}

/**
 * Parameters are sent as strings, so numbers, booleans and dates are accepted
 * for string parameters as well.
 *
 * @param {any} param
 * @param {string} indent
 */
function queryParamType(param, indent) {
  const type = schemaToType(param.schema ?? {}, indent);
  if (type !== "string") return type;
  return param.in === "query"
    ? "string | number | boolean | Date"
    : "string | number";
}

/**
 * @param {any} schema
 * @param {string} indent
 * @returns {string}
 */
function schemaToType(schema, indent) {
  const type = baseType(schema, indent);
  return schema.nullable ? `${type} | null` : type;
}

/**
 * @param {any} schema
 * @param {string} indent
 * @returns {string}
 */
function baseType(schema, indent) {
  if (schema.$ref) return schema.$ref.split("/").pop();

  if (schema.allOf) {
    return schema.allOf
      .map((/** @type {any} */ s) => {
        const type = schemaToType(s, indent);
        return type.includes("|") ? `(${type})` : type;
      })
      .join(" & ");
  }

  if (schema.enum) {
    return schema.enum
      .map((/** @type {any} */ v) => JSON.stringify(v))
      .join(" | ");
  }

  switch (schema.type) {
    case "string":
      return "string";
    case "number":
    case "integer":
      return "number";
    case "boolean":
      return "boolean";
    case "array": {
      if (!schema.items) return "unknown[]";
      const items = schemaToType(schema.items, indent);
      return /[|&\s]/.test(items) && !items.startsWith("{")
        ? `(${items})[]`
        : `${items}[]`;
    }
    case "object":
    default:
      if (schema.properties) return objectType(schema, indent);
      return schema.type === "object" ? "Record<string, unknown>" : "unknown";
  }
}

/**
 * @param {any} schema
 * @param {string} indent
 */
function objectType(schema, indent) {
  const required = schema.required ?? [];
  const properties = Object.entries(schema.properties).map(([name, prop]) => {
    const doc = prop.description
      ? `${docComment(prop.description, `${indent}  `)}\n`
      : "";
    const optional = required.includes(name) ? "" : "?";
    return `${doc}${indent}  ${propertyName(name)}${optional}: ${schemaToType(prop, `${indent}  `)};`;
  });
  if (!properties.length) return "{}";
  return `{\n${properties.join("\n")}\n${indent}}`;
}

/**
 * @param {string} text
 * @param {string} indent
 */
function docComment(text, indent) {
  const lines = text.replaceAll("*/", "*\\/").split("\n");
  if (lines.length === 1) return `${indent}/** ${lines[0]} */`;
  return [
    `${indent}/**`,
    ...lines.map((line) => `${indent} * ${line}`.trimEnd()),
    `${indent} */`,
  ].join("\n");
}

// ── Helpers ────────────────────────────────────────────────────────────────

/** @param {string} name */
function propertyName(name) {
  return /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
}

/** @param {string} value */
function camelCase(value) {
  const words = splitWords(value);
  return words.map((word, i) => (i === 0 ? word : capitalize(word))).join("");
}

/** @param {string} value */
function kebabCase(value) {
  return splitWords(value).join("-");
}

/**
 * Splits "two-factor-authentication", "HdmRoot" or "Ticket" into lowercase
 * words.
 *
 * @param {string} value
 */
function splitWords(value) {
  return value
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((word) => word.toLowerCase());
}

/** @param {string} value */
function capitalize(value) {
  return value.charAt(0).toUpperCase() + value.slice(1);
}
